import {createRequire} from 'node:module';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {resolve,sep} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(process.env.BROWSER_MODULE_ROOT+'/package.json');
const {chromium}=require('playwright');
const root=resolve('dist');
const server=createServer(async(req,res)=>{try{const pathname=decodeURIComponent(new URL(req.url,'http://localhost').pathname);const file=resolve(root,'.'+(pathname==='/'?'/index.html':pathname));if(!file.startsWith(root+sep)){res.writeHead(403);res.end();return}const data=await readFile(file);res.writeHead(200,{'Content-Type':file.endsWith('.mjs')||file.endsWith('.js')?'application/javascript':file.endsWith('.json')?'application/json':'text/html'});res.end(data)}catch{res.writeHead(404);res.end()}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/signals.json',route=>route.fulfill({json:{generated_at:'2026-10-26T08:00:00Z',signals:[{country:'India',topic:'Small business & ecommerce',title:'India shop research example',url:'https://news.google.com/example',publisher:'Test publisher',published_at:'2026-10-26T07:00:00Z'},{country:'United States',topic:'AI & automation',title:'US automation example',url:'https://news.google.com/other',publisher:'Test publisher',published_at:'2026-10-26T07:00:00Z'}],errors:[]}}));
 await page.route('**/ideas.json',route=>route.fulfill({json:{generated_at:'2026-10-26T08:00:00Z',ideas:[{country:'India',topic:'Small business & ecommerce',title:'Digital shop operations pilot — India',keywords:['dukaan','kirana'],evidence_status:'Demand not validated',method:'Template-based exploration brief; not AI-generated',sources:[]}]}}));
 await page.route('**/reddit.json',route=>route.fulfill({json:{generated_at:'2026-10-26T08:00:00Z',posts:[{title:'Delivery rant with slow service',url:'https://www.reddit.com/r/india/comments/abc/delivery/',subreddit:'india',num_comments:150}],errors:[]}}));
 await page.goto(`http://127.0.0.1:${server.address().port}/`,{waitUntil:'domcontentloaded'});
 await page.getByText('India shop research example').waitFor();
 await page.getByText('Digital shop operations pilot — India').waitFor();
 assert.equal(await page.locator('#generateIdeas').isDisabled(),false);
 await page.fill('#aiQuery','Dukaan');await page.locator('#generateIdeas').click();assert.equal(await page.locator('#aiResults .generated-idea').count(),1);
 await page.fill('#aiQuery','unrelatedkeyword');await page.locator('#generateIdeas').click();assert.equal(await page.locator('#aiResults .generated-idea').count(),0);
 await page.fill('#aiQuery','');await page.locator('#generateIdeas').click();
 await page.selectOption('#dynamicCountry','United States');await page.getByText('US automation example').waitFor();
 assert.equal(await page.getByText('India shop research example').count(),0);
 await page.selectOption('#country','India');assert.equal(await page.locator('#grid article').count(),10);
 await page.fill('#search','workflow');assert.equal(await page.locator('#grid article').count(),1);
 await page.locator('#grid [data-view]').click();assert.equal(await page.locator('dialog').isVisible(),true);
 await page.keyboard.press('Escape');assert.equal(await page.locator('dialog').isVisible(),false);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Mobile layout must not overflow horizontally');
 // Reddit discussions show genuine counts and direct search links, with honest empty states.
 await page.getByText('Delivery rant with slow service').waitFor();
 await page.fill('#redditQuery','delivery');await page.locator('#redditForm button').click();
 assert.equal(await page.locator('#redditPosts article').count(),1);
 assert.match(await page.locator('#redditPosts').innerText(),/150 comments at refresh/);
 await page.selectOption('#redditCommunity','india');
 assert.match(await page.locator('#redditExternal').getAttribute('href'),/reddit.com\/r\/india\/search/);
 await page.selectOption('#redditMinimum','1000');assert.equal(await page.locator('#redditPosts article').count(),0);
 assert.match(await page.locator('#redditPosts').innerText(),/No matching posts/);
 // Verify audit mode observes real fetch calls without changing their responses.
 assert.equal(await page.locator('#requestAudit').isHidden(),true);
 await page.locator('#auditToggle').click();
 await page.locator('#auditClear').click();
 await page.fill('#aiQuery','Dukaan');await page.locator('#generateIdeas').click();
 await page.locator('#auditEntries').getByText('Local UI action · No API request recorded.').first().waitFor();
 assert.equal(await page.locator('#auditEntries .audit-request').count(),0);
 await page.route('**/hn.algolia.com/api/v1/**',route=>route.fulfill({json:{nbHits:0,hits:[]}}));
 await page.route('**/en.wikipedia.org/w/api.php?**',route=>route.fulfill({json:['Dukaan',[],[],[]]}));
 await page.fill('#researchQuery','Dukaan');await page.locator('#researchForm button').click();
 await page.waitForFunction(()=>document.querySelectorAll('#auditEntries .audit-result').length===3&&[...document.querySelectorAll('#auditEntries .audit-result')].every(el=>el.textContent.includes('HTTP 200')));
 assert.match(await page.locator('#auditEntries').innerText(),/Click: Analyze idea/);
 assert.match(await page.locator('#auditEntries').innerText(),/hn.algolia.com/);
 await page.route('**/audit-fixture?**',route=>route.fulfill({json:{preserved:true}}));
 const body=await page.evaluate(()=>fetch('audit-fixture?token=secret-value&query=shops').then(r=>r.json()));
 assert.equal(body.preserved,true);
 assert.ok(!(await page.locator('#auditEntries').innerText()).includes('secret-value'));
 assert.match(await page.locator('#auditEntries').innerText(),/redacted/);
 const count=await page.locator('#auditEntries .audit-request').count();
 await page.locator('#auditToggle').click();
 await page.evaluate(()=>fetch('audit-fixture?query=disabled'));
 await page.locator('#auditToggle').click();
 assert.equal(await page.locator('#auditEntries .audit-request').count(),count);
 await page.locator('#auditClear').click();assert.equal(await page.locator('#auditEntries li').count(),0);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelectorAll('#auditEntries .audit-request').length>=2);
 assert.equal(await page.locator('#requestAudit').isVisible(),true);
 assert.match(await page.locator('#auditEntries').innerText(),/signals.json/);
 assert.match(await page.locator('#auditEntries').innerText(),/ideas.json/);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Audit panel must fit on mobile');
 await page.locator('#auditClose').click();assert.equal(await page.locator('#requestAudit').isHidden(),true);
 assert.deepEqual(errors,[]);
 console.log('Mobile browser smoke checks passed: news country filters, scheduled brief search, idea filters and dialog.');
}finally{await browser.close();await new Promise(r=>server.close(r))}
